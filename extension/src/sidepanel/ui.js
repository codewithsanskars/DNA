// Tiny DOM helpers. All dynamic text goes through textContent (never
// innerHTML), so nothing scraped from LinkedIn can inject markup.

const PROPS = new Set(['value', 'checked', 'selected', 'disabled', 'open', 'hidden']);

export function h(tag, attrs = {}, ...children) {
  const el = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs || {})) {
    if (v === undefined || v === null || v === false) {
      if (PROPS.has(k)) el[k] = false;
      continue;
    }
    if (k.startsWith('on') && typeof v === 'function') el.addEventListener(k.slice(2), v);
    else if (PROPS.has(k)) el[k] = v;
    else el.setAttribute(k, v === true ? '' : String(v));
  }
  for (const c of children.flat()) {
    if (c === null || c === undefined || c === false || c === '') continue;
    el.append(c instanceof Node ? c : document.createTextNode(String(c)));
  }
  return el;
}

