export function icon(name, cls = '') {
  const span = document.createElement('span');
  span.style.display = 'inline-flex';
  if (cls) span.className = cls;
  span.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name] || ''}</svg>`;
  const svg = span.firstChild;
  if (cls) svg.setAttribute('class', cls);
  return cls ? svg : span;
}

export function setIcon(el, name) {
  el.replaceChildren(icon(name));
}

export function initials(name) {
  return (
    String(name || '?')
      .split(/\s+/)
      .filter(Boolean)
      .slice(0, 2)
      .map((p) => p[0].toUpperCase())
      .join('') || '?'
  );
}

let toastTimer;
export function toast(message, isError = false) {
  const el = document.getElementById('toast');
  if (!el) return;
  el.textContent = message;
  el.className = `toast ${isError ? 'error' : ''}`;
  el.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => (el.hidden = true), isError ? 5000 : 3000);
}
